-- ASISTENCIA_EVENTO (evento_usuario) : mínimo 5.000 registros
-- Se generan 6.000 candidatos; la PK compuesta (usuario, evento) descarta duplicados.
-- ---------------------------------------------------------------------
WITH cand AS MATERIALIZED (
    SELECT g,
           _rand_miembro()                       AS u,
           1 + floor(random() * 3000)::int       AS ev
    FROM generate_series(1, 6000) AS g
)
INSERT INTO asistencia_evento (id_usuario, id_evento, fecha_registro, estado_asistencia)
SELECT c.u, e.id_evento,
       LEAST(LOCALTIMESTAMP, e.fecha_hora_inicio - random() * interval '30 days'),
       CASE WHEN e.fecha_hora_inicio > LOCALTIMESTAMP
                 THEN _pick(ARRAY['Inscrito','Inscrito','Inscrito','Cancelado'])
            ELSE _pick(ARRAY['Asistió','Asistió','Asistió','No asistió','Cancelado'])
       END
FROM cand c
JOIN evento e ON e.id_evento = c.ev
WHERE e.id_usuario_organizador <> c.u            -- el organizador no es participante de su propio evento
ON CONFLICT DO NOTHING;

