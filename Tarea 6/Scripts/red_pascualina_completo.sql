-- Elige un elemento al azar de un arreglo de texto
CREATE OR REPLACE FUNCTION _pick(a text[]) RETURNS text
LANGUAGE sql VOLATILE AS $$
    SELECT a[1 + floor(random() * array_length(a, 1))::int]
$$;

-- Devuelve el id de un usuario con rol "Miembro" (excluye administradores,
-- auxiliares y visitantes: ids 17501-17513 y 18501-18550)
CREATE OR REPLACE FUNCTION _rand_miembro() RETURNS integer
LANGUAGE plpgsql VOLATILE AS $$
DECLARE r integer;
BEGIN
    r := 1 + floor(random() * 18487)::int;      -- 18487 miembros posibles
    IF r >= 17501 THEN r := r + 13; END IF;     -- salta admin (3) y auxiliares (10)
    RETURN r;
END
$$;

-- Fecha/hora aleatoria entre (hoy - dias_atras) y (hoy + dias_adelante)
CREATE OR REPLACE FUNCTION _rand_ts(dias_atras integer, dias_adelante integer DEFAULT 0) RETURNS timestamp
LANGUAGE sql VOLATILE AS $$
    SELECT date_trunc('second',
           LOCALTIMESTAMP + (random() * (dias_atras + dias_adelante) - dias_atras) * interval '1 day')
$$;


