1.3.6. Agregar dos fechas de inicio y fin y controlar su orden


ALTER TABLE actividad_comunitaria
ADD COLUMN fecha_inicio DATE,
ADD COLUMN fecha_fin DATE,
ADD CONSTRAINT chk_actividad_fechas
CHECK (fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio);


1.3.7. Agregar un campo entero que no sea negativo

ALTER TABLE actividad_comunitaria
ADD COLUMN cupos INTEGER,
ADD CONSTRAINT chk_actividad_cupos_no_negativos
CHECK (cupos IS NULL OR cupos >= 0);


