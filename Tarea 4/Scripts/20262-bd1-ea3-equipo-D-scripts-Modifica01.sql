1.3.1. Crear una tabla nueva coherente con el sistema


CREATE TABLE convocatoria (
    id_convocatoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(100),
    presupuesto NUMERIC(10,2),
    observaciones TEXT
);


